#!/usr/bin/env node
/**
 * Regenerate mutations.md from a 1Panel swagger spec.
 *
 *   node generate.mjs <swagger.json> [--version=v2.3.2] [--out=mutations.md]
 *
 * Get the spec for the version the panel reports (systemVersion), straight from
 * the release tag — that file is the one compiled into the panel binary:
 *
 *   curl -sSL -o /tmp/sw.json \
 *     https://raw.githubusercontent.com/1Panel-dev/1Panel/v2.3.2/core/cmd/server/docs/swagger.json
 *
 * No dependencies. The table is derived, never hand-written: every field name,
 * required flag and enum below comes from the spec.
 */

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const specPath = args.find((a) => !a.startsWith('--'));
const flag = (name, fallback) => {
  const hit = args.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : fallback;
};
if (!specPath) {
  console.error('usage: node generate.mjs <swagger.json> [--version=v2.3.2] [--out=mutations.md]');
  process.exit(2);
}

const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));
const version = flag('version', '(unknown — pass --version=<panel systemVersion>)');
const out = path.resolve(flag('out', path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), 'mutations.md')));

/** module, method, path, reservedMutations id */
const ENDPOINTS = [
  ['monitoring', 'POST', '/hosts/monitor/setting/update', 'updateMonitorSetting'],
  ['monitoring', 'POST', '/hosts/monitor/clean', 'cleanMonitorData'],
  ['websites', 'POST', '/websites', 'createWebsite'],
  ['websites', 'POST', '/websites/update', 'updateWebsite'],
  ['websites', 'POST', '/websites/operate', 'operateWebsite'],
  ['websites', 'POST', '/websites/del', 'deleteWebsite'],
  ['websites', 'POST', '/websites/:id/https', 'updateHttpsConfig'],
  ['websites', 'POST', '/websites/ssl/update', 'updateCertificate'],
  ['apps', 'POST', '/apps/install', 'installApp'],
  ['apps', 'POST', '/apps/installed/op', 'operateInstalledApp'],
  ['apps', 'POST', '/apps/installed/params/update', 'updateAppInstallParams'],
  ['containers', 'POST', '/containers', 'createContainer'],
  ['containers', 'POST', '/containers/update', 'updateContainer'],
  ['containers', 'POST', '/containers/operate', 'operateContainer'],
  ['logs', 'POST', '/core/logs/clean', 'cleanLogs'],
  ['cronjobs', 'POST', '/cronjobs', 'createCronjob'],
  ['cronjobs', 'POST', '/cronjobs/update', 'updateCronjob'],
  ['cronjobs', 'POST', '/cronjobs/status', 'updateCronjobStatus'],
  ['cronjobs', 'POST', '/cronjobs/handle', 'handleCronjobOnce'],
  ['nodes', 'POST', '/core/licenses/bind/free', 'changeBind'],
];

const DESTRUCTIVE = /^(delete|forceDelete|deleteDB|deleteBackup|deleteImage|remove|clean)/;

function bodyRef(p) {
  const op = spec.paths?.[p]?.post;
  const ref = op?.parameters?.find((x) => x.in === 'body')?.schema?.$ref;
  return { op, ref: ref?.split('/').pop() };
}

/** Stable text signature of one endpoint's request shape, for drift detection. */
function signature(p) {
  const { op, ref } = bodyRef(p);
  if (!op) return 'MISSING';
  if (!ref) return 'no-body';
  const def = spec.definitions?.[ref];
  if (!def) return `ref-without-def(${ref})`;
  const fields = Object.entries(def.properties ?? {})
    .map(([k, v]) => `${k}:${v.type ?? (v.$ref ? v.$ref.split('/').pop() : '?')}${v.enum ? '=' + JSON.stringify(v.enum) : ''}`)
    .sort()
    .join(',');
  return `${ref}[req=${(def.required ?? []).join('|')}]{${fields}}`;
}

const fingerprint = `sha256:${createHash('sha256')
  .update(ENDPOINTS.map(([, , p]) => `${p} ${signature(p)}`).join('\n'))
  .digest('hex')}`;

const nested = new Map();
function typeOf(v) {
  if (!v) return '?';
  if (v.$ref) {
    const name = v.$ref.split('/').pop();
    if (!nested.has(name)) nested.set(name, spec.definitions?.[name]);
    return name;
  }
  if (v.type === 'array') {
    const item = v.items?.$ref ? v.items.$ref.split('/').pop() : (v.items?.type ?? '?');
    if (v.items?.$ref && !nested.has(item)) nested.set(item, spec.definitions?.[item]);
    return `array<${item}>`;
  }
  return v.type ?? '?';
}

const bodyRefs = new Set();
const lines = [];
lines.push('# 1Panel mutation request shapes');
lines.push('');
lines.push('```');
lines.push(`panel version : ${version}`);
lines.push(`spec source   : core/cmd/server/docs/swagger.json @ tag ${version}`);
lines.push(`swagger       : ${spec.swagger ?? '?'}   basePath ${spec.basePath ?? '?'}`);
lines.push(`shapes digest : ${fingerprint}`);
lines.push('```');
lines.push('');
lines.push('Generated by `generate.mjs` from the spec that ships inside the panel. Field names,');
lines.push('required flags and enums are read out of that file — never written from memory.');
lines.push('Do not hand-edit.');
lines.push('');
lines.push('## Scope');
lines.push('');
lines.push('Valid only for the panel version above: it is the request shapes of that specific');
lines.push('version. SKILL.md owns the gate that decides when this file may be used; never write');
lines.push('from it for a panel reporting a different version, and never from memory.');
lines.push('');
lines.push('```bash');
lines.push('curl -sSL -o /tmp/sw.json \\');
lines.push('  https://raw.githubusercontent.com/1Panel-dev/1Panel/<version>/core/cmd/server/docs/swagger.json');
lines.push('node generate.mjs /tmp/sw.json --version=<version>');
lines.push('```');
lines.push('');
lines.push('`*` required · `enum=[...]` only accepted values · **cascade** destroys something else');
lines.push('as a side effect and must be decided by the user, never defaulted.');
lines.push('');

for (const [module, method, p, id] of ENDPOINTS) {
  const { op, ref } = bodyRef(p);
  lines.push(`## ${module} / ${id}`);
  lines.push('');
  lines.push(`### \`${method} ${spec.basePath ?? '/api/v2'}${p}\``);
  lines.push('');
  if (!op) {
    lines.push('**NOT IN THE SPEC for this version.** Declared by `reservedMutations` but absent, so');
    lines.push('it is not callable here (most likely XPack/Pro only). Do not attempt it and do not');
    lines.push('guess a body.');
    lines.push('');
    continue;
  }
  lines.push(`*${op.summary ?? id}*`);
  lines.push('');
  if (!ref) {
    lines.push('Body: **none**. Send the request without `--body-json`.');
    lines.push('');
    continue;
  }
  const def = spec.definitions?.[ref] ?? {};
  const props = def.properties ?? {};
  const required = def.required ?? [];
  bodyRefs.add(ref);
  lines.push(`Body \`${ref}\`: ${required.length} required of ${Object.keys(props).length} fields.`);
  lines.push('');
  lines.push('| field | type | |');
  lines.push('| --- | --- | --- |');
  for (const [key, value] of Object.entries(props)) {
    const notes = [];
    if (required.includes(key)) notes.push('**required**');
    if (value.enum) notes.push(`enum=\`${JSON.stringify(value.enum)}\``);
    if (DESTRUCTIVE.test(key) && value.type === 'boolean') notes.push('**cascade**');
    lines.push(`| \`${key}\` | ${typeOf(value)} | ${notes.join(' ')} |`);
  }
  lines.push('');
  if (p.includes('/:id/')) {
    lines.push(`> The path uses \`:id\` but the body field is named \`${required[0] ?? '(see table)'}\` —`);
    lines.push('> do not assume they match.');
    lines.push('');
  }
}

lines.push('## Nested structures');
lines.push('');
lines.push('Referenced by the bodies above.');
lines.push('');
for (const [name, def] of [...nested.entries()].sort()) {
  if (bodyRefs.has(name) || !def) continue;
  const required = def.required ?? [];
  lines.push(`### ${name}`);
  lines.push('');
  lines.push(
    Object.entries(def.properties ?? {})
      .map(([k, v]) => `\`${k}\`${required.includes(k) ? '*' : ''}: ${typeOf(v)}${v.enum ? ` enum=${JSON.stringify(v.enum)}` : ''}`)
      .join(', '),
  );
  lines.push('');
}

fs.writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`wrote ${out}`);
console.log(`  version ${version} | digest ${fingerprint} | ${lines.length} lines`);
